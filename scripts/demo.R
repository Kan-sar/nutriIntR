source("scripts/load_project.R")
input <- jsonlite::fromJSON("inst/extdata/example.json", simplifyVector = FALSE)
result <- analyze_interactions(input$events, input$context, input$interpolate)
dir.create("reports/generated", recursive = TRUE, showWarnings = FALSE)
writeLines(result_json(result), "reports/generated/example-result.json")
clock_input <- jsonlite::fromJSON("inst/extdata/example-clock.json", simplifyVector = FALSE)
clock_result <- analyze_interactions(clock_input$events, clock_input$context,
  medications = clock_input$medications)
writeLines(result_json(clock_result), "reports/generated/clock-result.json")
grDevices::png("reports/generated/timeline.png", width = 1200, height = 700, res = 120)
plot_timeline(result)
grDevices::dev.off()
grDevices::png("reports/generated/network.png", width = 1100, height = 800, res = 120)
plot_network(result)
grDevices::dev.off()
grDevices::png("reports/generated/phytate-study.png", width = 1100, height = 700, res = 120)
plot_phytate_curve(TRUE, result = result)
grDevices::dev.off()
grDevices::png("reports/generated/medication-network.png", width = 1200, height = 760, res = 120)
plot_medication_network(clock_result)
grDevices::dev.off()
grDevices::png("reports/generated/drug-network.png", width = 1100, height = 760, res = 120)
plot_drug_network(clock_result)
grDevices::dev.off()
cat("Created JSON and five plots in reports/generated/.\n")

intake_clock <- function(id, label) tags$div(class = "form-group",
  tags$label(`for` = id, label), tags$input(id = id, type = "time", class = "form-control",
    value = "", step = "60", onchange = sprintf("Shiny.setInputValue('%s', this.value, {priority:'event'});", id)))

